#!/usr/bin/env node
// Regenerates public/sitemap.xml from src/content/maco.ts — replaces the
// hand-maintained list that both CONTEXT.md and sitemap.xml's own comment
// flagged as a staleness risk. Wired into `build` (see package.json); needs
// Node's --experimental-strip-types since content/maco.ts is plain typed
// data (no imports, no non-erasable syntax) with no build step of its own.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { services, projects, products, site } from "../src/content/maco.ts";

const SITE_URL = "https://www.maco.codes";

const staticPaths = ["/", "/about", "/services", "/work", "/products", "/clients", "/contact"];
const paths = [
  ...staticPaths,
  ...services.map((s) => `/services/${s.slug}`),
  ...projects.map((p) => `/work/${p.slug}`),
  ...products.map((p) => `/products/${p.slug}`),
];

// Case-study URLs also list their real screenshots, for image search.
const galleries = new Map(projects.map((p) => [`/work/${p.slug}`, p.gallery ?? []]));
const urls = paths
  .map((p) => {
    const images = (galleries.get(p) ?? [])
      .map((src) => `<image:image><image:loc>${SITE_URL}${src}</image:loc></image:image>`)
      .join("");
    return `  <url><loc>${SITE_URL}${p}</loc>${images}</url>`;
  })
  .join("\n");
const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-sitemap.mjs from src/content/maco.ts — do not hand-edit. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${urls}
</urlset>
`;

const out = fileURLToPath(new URL("../public/sitemap.xml", import.meta.url));
writeFileSync(out, xml);

// A plain summary for AI assistants, from the same content so it can't drift.
const llms = `# MaCo

> ${site.category} based in ${site.location}. ${site.tagline}

${site.statement}

Contact: ${site.contact_email}

## Services

${services.map((s) => `- [${s.title}](${SITE_URL}/services/${s.slug}): ${s.short_description}`).join("\n")}

## Client work

${projects.map((p) => `- [${p.title}](${SITE_URL}/work/${p.slug}): ${p.short_description}`).join("\n")}

## Products

${products.map((p) => `- [${p.title}](${SITE_URL}/products/${p.slug}): ${p.short_description}`).join("\n")}

## Company

- [About](${SITE_URL}/about)
- [Clients](${SITE_URL}/clients)
- [Contact](${SITE_URL}/contact)
`;
writeFileSync(fileURLToPath(new URL("../public/llms.txt", import.meta.url)), llms);
console.log(`sitemap.xml written (${paths.length} URLs)`);
